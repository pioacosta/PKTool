#pragma once

#include <cstdint>

#include "core/pokemon/pokemon.h"

// PID/IV correlations of the special Gen III generators, ported from PKHeX
// (MethodFinder, CommonEvent3, ChannelJirachi, MethodCXD):
//   - B-A-C-D: event gifts draw the PID with its halves swapped relative to
//     Method 1 (high half first), then the two IV words;
//   - the Pokemon Channel Jirachi and every Colosseum/XD Pokemon use the
//     XD RNG, a different linear congruential generator.
// "Origin seed" is the RNG state just before the first call of the sequence.
namespace pktool::legality::rng3 {

inline uint32_t lcNext(uint32_t s) { return s * 0x41C64E6Du + 0x6073u; }
inline uint32_t lcPrev(uint32_t s) { return s * 0xEEB9EB65u + 0x0A3561A1u; }
inline uint32_t xdNext(uint32_t s) { return s * 0x343FDu + 0x269EC3u; }
inline uint32_t xdPrev(uint32_t s) { return s * 0xB9B33155u + 0xA170F641u; }

// 15-bit IV words of an IV array (hp/atk/def, then spe/spa/spd).
uint32_t ivWord1(const uint8_t ivs[pokemon::kStatCount]);
uint32_t ivWord2(const uint8_t ivs[pokemon::kStatCount]);

// ---------------------------------------------------------------- B-A-C-D

enum class BacdType : uint8_t {
    Regular,      // PID = (A << 16) | B
    Anti,         // Regular PID that was shiny, moved to the next non-shiny PID
    AntiXor,      // high half xor-ed with the trainer ID so it cannot be shiny
    ForceShiny,   // low bits and high half forced to make it shiny
};

struct BacdMatch {
    BacdType type;
    uint32_t origin;
};

// Every B-A-C-D frame that produces `pid` and `ivs` (for a trainer whose
// TID xor SID is `idXor`). Returns the count written to `out` (at most `max`).
int findBacd(uint32_t pid, const uint8_t ivs[pokemon::kStatCount], uint32_t idXor, BacdMatch* out, int max);

// PID of a BACD frame: Regular = (A << 16) | B, anti-shiny and force-shiny
// variants like the games' event scripts.
uint32_t bacdRegular(uint32_t a16, uint32_t b16);
uint32_t bacdAntiShiny(uint32_t pid, uint32_t idXor);                       // regular, pushed to non-shiny
uint32_t bacdAntiXor(uint32_t a16, uint32_t b16, uint32_t idXor);          // a16 must be >= 8
uint32_t bacdForceShiny(uint32_t x16, uint32_t b16, uint32_t idXor);

// OT gender a B-A-C-D event's RNG implies for its `rule` (data::EventOtGender3),
// from the frame's origin seed; -1 for rules that do not come from the RNG
// (Recipient, RandAlgo).
int bacdOtGender(uint8_t rule, uint32_t origin);

// MYSTRY Mew: is `origin` one of the distribution's frames? Mirrors PKHeX's
// MystryMew checks (86 seeds, each with 4 further PID/IV frames).
bool mystryMewOrigin(uint32_t origin);

// ------------------------------------------------------------ Channel Jirachi

struct ChannelFrame {
    uint32_t pid;
    uint8_t ivs[pokemon::kStatCount];
    uint16_t sid;
    uint16_t heldItem3;  // Gen III item ID: 169 Ganlon Berry or 170 Salac Berry
    uint8_t version;     // 1 = Sapphire, 2 = Ruby
    uint8_t otGender;
};

// The PID/IV frame generated by the XD RNG at `seed` (just after the menu).
ChannelFrame channelFrame(uint32_t seed);
// From an arbitrary seed, advance to a seed the game can reach.
uint32_t channelSkipToPidIv(uint32_t seed);
// True if `pid`/`ivs` come from a reachable Channel frame for this trainer.
bool matchChannel(uint32_t pid, const uint8_t ivs[pokemon::kStatCount], uint16_t sid, uint8_t version, uint8_t otGender);

// ------------------------------------------------------- Colosseum / XD (CXD)

enum class CxdType : uint8_t { None, Plain, Anti };

// PID/IV frame of Colosseum/XD Pokemon: two IV words, an ability call, then
// the PID (rerolled with the next pair when it would be shiny, "Anti").
CxdType findCxd(uint32_t pid, const uint8_t ivs[pokemon::kStatCount], uint16_t tid, uint16_t sid);

// Every frame that explains the PID/IVs; `origin` is the state just before the
// first IV call (PKHeX's origin seed, what the shadow locks are checked from).
struct CxdMatch {
    CxdType type;
    uint32_t origin;
};
int findCxdAll(uint32_t pid, const uint8_t ivs[pokemon::kStatCount], uint16_t tid, uint16_t sid, CxdMatch* out, int max);

// States just before the call that drew the PID's high half (the e-Reader
// shadows have no IV correlation, only their PID is searched).
int pidOrigins(uint32_t pid, uint32_t* out, int max);

// XD Poke Spot: the PID comes from an encounter of `slot` (0-2) and the IVs
// from a valid animation sequence (PKHeX MethodPokeSpot.TryGetOriginSeeds).
bool matchPokeSpot(uint32_t pid, const uint8_t ivs[pokemon::kStatCount], uint8_t slot);
// Generation side: is `seed` (the state before the PID's high half) a valid
// encounter of `slot`; the IVs/ability of the frame whose pre-IV state is `preIv`
// (false when the animation rolls before it are impossible).
bool pokeSpotActivation(uint8_t slot, uint32_t seed);
bool pokeSpotIvFrame(uint32_t preIv, uint8_t ivs[pokemon::kStatCount], uint8_t* abilityBit);

// The starter frames tied to the trainer IDs (false when no RNG state draws
// these IDs): same call structure as matchColoStarter / matchXdStarter.
bool coloStarterFrame(uint16_t tid, uint16_t sid, uint16_t species, uint32_t* pid, uint8_t ivs[pokemon::kStatCount],
                      uint8_t* abilityBit);
bool xdStarterFrame(uint16_t tid, uint16_t sid, uint32_t* pid, uint8_t ivs[pokemon::kStatCount], uint8_t* abilityBit);

// Colosseum's Umbreon (197) / Espeon (196) and XD's Eevee: their frame is tied
// to the trainer IDs, which the games draw first.
bool matchColoStarter(uint32_t pid, const uint8_t ivs[pokemon::kStatCount], uint16_t tid, uint16_t sid, uint16_t species);
bool matchXdStarter(uint32_t pid, const uint8_t ivs[pokemon::kStatCount], uint16_t tid, uint16_t sid);

}  // namespace pktool::legality::rng3
