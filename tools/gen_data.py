def gen_learn3(core: Path, out: Path) -> None:
    """Gen III learnsets (R/S, E, FR/LG combined) and move PP."""
    res = core / "Resources" / "byte"
    moves = {sp: {} for sp in range(MAX_SPECIES_G3 + 1)}

    def add(sp, move, flag, level=0):
        if move == 0 or move > 354:
            return
        entry = moves[sp].setdefault(move, [0, 255])
        entry[0] |= flag
        if flag == SRC_LEVEL:
            entry[1] = min(entry[1], level)

    for name, ident in (("rs", b"rs"), ("e", b"em"), ("fr", b"fr"), ("lg", b"lg")):
        entries = binlinker((res / "levelup" / f"lvlmove_{name}.pkl").read_bytes(), ident, False)
        for sp in range(1, min(len(entries), MAX_SPECIES_G3 + 1)):
            blob = entries[sp]
            count = len(blob) // 3
            mv = struct.unpack_from(f"<{count}H", blob, 0)
            for m, l in zip(mv, blob[count * 2:count * 3]):
                add(sp, m, SRC_LEVEL, l)
    entries = binlinker((res / "eggmove" / "eggmove_rs.pkl").read_bytes(), b"rs", False)
    for sp in range(1, min(len(entries), MAX_SPECIES_G3 + 1)):
        blob = entries[sp]
        for m in struct.unpack_from(f"<{len(blob) // 2}H", blob, 0):
            add(sp, m, SRC_EGG)
    machines = binlinker((res / "personal" / "hmtm_g3.pkl").read_bytes(), b"g3", True)
    tutors = binlinker((res / "personal" / "tutors_g3.pkl").read_bytes(), b"g3", True)
    for sp in range(1, MAX_SPECIES_G3 + 1):
        for flags, table, source in ((machines[sp], TM_MOVES3 + HM_MOVES3, SRC_MACHINE),
                                     (tutors[sp], TUTOR_MOVES3, SRC_TUTOR)):
            for i, m in enumerate(table):
                if i >> 3 < len(flags) and flags[i >> 3] & (1 << (i & 7)):
                    add(sp, m, source)
    for move, species in SPECIAL_TUTORS3.items():
        for sp in species:
            add(sp, move, SRC_TUTOR)
    add(172, 344, SRC_EGG)  # Volt Tackle: Pichu eggs from a parent holding a Light Ball (Emerald)

    pp = parse_int_table((core / "Moves" / "MoveInfo3.cs").read_text(encoding="utf-8"), "PP")
    for sp in moves:
        for entry in moves[sp].values():
            if not entry[0] & SRC_LEVEL:
                entry[1] = 0
    stream, index = pack_learnsets(moves, MAX_SPECIES_G3)
    count = sum(len(m) for m in moves.values())

    def rows(values, per):
        return "\n".join("    " + ", ".join(str(v) for v in values[i:i + per]) + "," for i in range(0, len(values), per))

    content = HEADER + '\n#include "core/data/learn3.h"\n\nnamespace pktool::data::generated {\n\n'
    content += "// Moves each species can learn in Gen III (union of R/S, E and FR/LG), sorted by move\n"
    content += "// and packed as described in core/data/learn4.h.\n"
    content += "const uint8_t kLearn3[] = {\n" + learn_stream_rows(stream) + "\n};\n\n"
    content += "// kLearn3 range of species s: [kLearn3Index[s], kLearn3Index[s + 1]).\n"
    content += "const uint32_t kLearn3Index[] = {\n" + rows(index, 16) + "\n};\n\n"
    content += "// Base PP of moves 0-354 in Gen III.\n"
    content += "const uint8_t kPp3[] = {\n" + rows(pp, 20) + "\n};\n"
    content += f"const int kPp3Count = {len(pp)};\n"
    content += "\n}  // namespace pktool::data::generated\n"
    (out / "learn3_data.cpp").write_text(content, encoding="ascii")
    print(f"learn3: {count} entries in {len(stream)} bytes, {len(pp)} moves")


