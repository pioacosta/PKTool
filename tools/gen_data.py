    for national in range(1, MAX_SPECIES_G3 + 1):
        shift = national - 252
        internal = national + to_internal[shift] if 0 <= shift < len(to_internal) else national
        national_of[internal] = national
    internal_to_national = [national_of.get(i, 0) for i in range(max(national_of) + 1)]

