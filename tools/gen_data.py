def gen_bag12(core: Path, out: Path) -> None:
    """Game Boy bag pockets (PKHeX ItemStorage1/2, PlayerBag1/2). The slot offsets differ per
    save variant and live in the save classes; the offset column is 0."""
    st1 = parse_item_spans((core / "Items" / "ItemStorage1.cs").read_text(encoding="utf-8"))
    st2 = parse_item_spans((core / "Items" / "ItemStorage2.cs").read_text(encoding="utf-8"))
    bag1 = (core / "Items" / "Bags" / "PlayerBag1.cs").read_text(encoding="utf-8")
    bag2 = (core / "Items" / "Bags" / "PlayerBag2.cs").read_text(encoding="utf-8")
    pouch = r"new\(offsets\.\w+, (\d+), (\d+), info, (\w+)\)"
    sizes1 = {kind: (int(n), int(m)) for n, m, kind in re.findall(pouch, bag1)}
    sizes2 = {kind: (int(n), int(m)) for n, m, kind in re.findall(pouch, bag2)}
    general1 = [v for v in st1["General"] if v != 0]
    # PKHeX: PCItemsC = General + Balls + Machine + KeyCrystal; Gold/Silver drops the last 4 key items.
    pc_c = st2["General"] + st2["Balls"] + st2["Machine"] + st2["KeyCrystal"]
    layouts = {
        "Gen1": [("Items", general1, sizes1["Items"], "Items"), ("PC Items", general1, sizes1["PCItems"], "Items")],
    }
    # PKHeX lets the key item list hold 26, but the game stores 25 (count + 25 + terminator = 27
    # bytes before the Balls count); a 26th entry would put its terminator over that count.
    key_slots = (min(sizes2["KeyItems"][0], 25), sizes2["KeyItems"][1])
    for name, key, pc in (("Gen2GS", "KeyGS", pc_c[:-4]), ("Gen2C", "KeyCrystal", pc_c)):
        layouts[name] = [
            ("Items", st2["General"], sizes2["Items"], "Items"),
            ("Key Items", st2[key], key_slots, "KeyItems"),
            ("Balls", st2["Balls"], sizes2["Balls"], "Balls"),
            ("TMs & HMs", st2["Machine"], sizes2["TMHMs"], "TMsHMs"),
            ("PC Items", pc, sizes2["PCItems"], "Items"),
        ]
    tables, specs = "", ""
    for layout, pockets in layouts.items():
        rows = []
        for label, ids, (capacity, max_count), enum in pockets:
            if len(set(ids)) != len(ids):
                raise SystemExit(f"{layout} {label}: duplicate item IDs")
            var = f"k{layout}{enum}{len(rows)}"
            tables += f"const uint16_t {var}[] = {{\n"
            tables += ",\n".join("    " + ", ".join(str(v) for v in ids[i:i + 16]) for i in range(0, len(ids), 16))
            tables += ",\n};\n"
            rows.append(f"    {{{c_string(label)}, PocketKind::{enum}, 0, {capacity}, {max_count}, 0, 0, {var}, {len(ids)}}},")
        specs += f"const PocketSpec kBag{layout}[] = {{\n" + "\n".join(rows) + "\n};\n"
        specs += f"const int kBag{layout}Count = {len(rows)};\n\n"
    content = HEADER + '\n#include "core/data/items.h"\n\nnamespace pktool::data::generated {\n\n'
    content += tables + "\n" + specs + "}  // namespace pktool::data::generated\n"
    (out / "bag12_data.cpp").write_text(content, encoding="ascii")
    print("bag12:", ", ".join(f"{k} {len(v)}" for k, v in layouts.items()))


