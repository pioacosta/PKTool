# Gen IV PK4 block orders (shuffle value -> block positions), from PKHeX.
PK4_BLOCK_POSITION = [
    (0, 1, 2, 3), (0, 1, 3, 2), (0, 2, 1, 3), (0, 3, 1, 2), (0, 2, 3, 1), (0, 3, 2, 1),
    (1, 0, 2, 3), (1, 0, 3, 2), (2, 0, 1, 3), (3, 0, 1, 2), (2, 0, 3, 1), (3, 0, 2, 1),
    (1, 2, 0, 3), (1, 3, 0, 2), (2, 1, 0, 3), (3, 1, 0, 2), (2, 3, 0, 1), (3, 2, 0, 1),
    (1, 2, 3, 0), (1, 3, 2, 0), (2, 1, 3, 0), (3, 1, 2, 0), (2, 3, 1, 0), (3, 2, 1, 0),
]
EVENT_DATES_CSV = Path(__file__).resolve().parent / "event_dates.csv"


def load_event_dates(gen: int) -> list[dict]:
    """Distribution periods collected by tools/fetch_event_dates.py (Bulbapedia)."""
    with EVENT_DATES_CSV.open(encoding="utf-8", newline="") as f:
        return [row for row in csv.DictReader(f) if int(row["gen"]) == gen]


def name_key(name: str) -> str:
    return unicodedata.normalize("NFKC", name).casefold().replace(" ", "")


def match_periods(rows: list[dict], language: int, species: int, fixed_trainer: bool, ot: str, tid: int,
                  level: int) -> list[tuple[date, date]]:
    """Distribution periods of the card with these traits.

    `fixed_trainer` is false when the card gives the receiving trainer's OT;
    `ot` may be empty when it cannot be decoded; `language` 0 matches any
    language. Rows are narrowed by trainer ID, OT and level while that leaves
    some; the periods of all the rows left are returned.
    """
    candidates = [r for r in rows if int(r["species"]) == species and (language == 0 or int(r["language"]) == language)]
    if fixed_trainer:
        candidates = [r for r in candidates if r["tid"] and int(r["tid"]) == tid]
    else:
        candidates = [r for r in candidates if not r["tid"]]
    narrowers = [lambda r: r["level"] == str(level)]
    if ot:
        narrowers.insert(0, lambda r: name_key(r["ot"]) == name_key(ot))
    for narrow in narrowers:
        narrowed = [r for r in candidates if narrow(r)]
        if narrowed:
            candidates = narrowed
    periods = sorted({(date.fromisoformat(r["start"]), date.fromisoformat(r["end"])) for r in candidates})
    merged: list[tuple[date, date]] = []
    for start, end in periods:
        if merged and start <= merged[-1][1] + timedelta(days=1):
            merged[-1] = (merged[-1][0], max(merged[-1][1], end))
        else:
            merged.append((start, end))
    return merged


def emit_periods(name: str, periods: list[tuple[date, date]]) -> str:
    def ymd(d: date) -> str:
        return f"{{{d.year - 2000}, {d.month}, {d.day}}}"
    rows = [f"    {{{ymd(a)}, {ymd(b)}}}," for a, b in periods] or ["    {{0, 0, 0}, {0, 0, 0}},  // unused"]
    return f"const EventPeriod {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


PCD_SIZE = 0x358
LANGUAGE_CODES = {1: "JPN", 2: "ENG", 3: "FRE", 4: "ITA", 5: "GER", 7: "SPA", 8: "KOR"}


def pk4_checksum(data: bytes) -> int:
    return sum(struct.unpack_from("<64H", data, 8)) & 0xFFFF


def pk4_decrypt(data: bytes) -> bytes:
    pid, check = struct.unpack_from("<I2xH", data, 0)
    body = bytearray(data[8:136])
    seed = check
    for i in range(0, len(body), 2):
        seed = (seed * 0x41C64E6D + 0x6073) & 0xFFFFFFFF
        struct.pack_into("<H", body, i, struct.unpack_from("<H", body, i)[0] ^ (seed >> 16))
    order = PK4_BLOCK_POSITION[((pid >> 13) & 31) % 24]
    blocks = [bytes(body[i * 32:(i + 1) * 32]) for i in range(4)]
    return bytes(data[:8]) + b"".join(blocks[order[i]] for i in range(4))


def gen_events4(core: Path, out: Path, species_names: list[str]) -> None:
    """Pokemon Wonder Cards (PCD) from PKHeX's Mystery Gift database."""
    table = parse_char_table(
        (core / "PKM" / "Strings" / "StringConverter4Util.cs").read_text(encoding="utf-8"), "TableINT")
    data = (core / "Resources" / "legality" / "mgdb" / "wc4.pkl").read_bytes()
    dates = load_event_dates(4)
    cards = []
    for i in range(len(data) // PCD_SIZE):
        card = data[i * PCD_SIZE:(i + 1) * PCD_SIZE]
        if card[0] != 1:  # 1 = Pokemon gift (eggs, items and the Manaphy egg are skipped)
            continue
        template = card[8:8 + 136]
        species = struct.unpack_from("<H", template, 8)[0]
        if pk4_checksum(template) != struct.unpack_from("<H", template, 6)[0] or not 0 < species <= MAX_SPECIES_G4:
            template = pk4_decrypt(template)
        species = struct.unpack_from("<H", template, 8)[0]
        if pk4_checksum(template) != struct.unpack_from("<H", template, 6)[0] or not 0 < species <= MAX_SPECIES_G4:
            raise SystemExit(f"wc4 card {i}: bad Pokemon template")
        language = template[0x17]
        title = ""
        for (value,) in struct.iter_unpack("<H", card[0x104:0x104 + 0x48]):
            if value == 0xFFFF or value >= len(table):
                break
            title += chr(table[value]) if table[value] != 0xFFFF else "?"
        title = " ".join(title.split())
        # The DS fonts cover Latin text only: other titles get a generic name.
        if not title or any(ord(ch) > 0x24F for ch in title):
            title = f"{species_names[species]} event"
        card_id = struct.unpack_from("<H", card, 0x150)[0]
        ot = ""  # stays empty for names outside the table (Korean)
        for (value,) in struct.iter_unpack("<H", template[0x68:0x68 + 16]):
            if value == 0xFFFF or value >= len(table) or table[value] == 0xFFFF:
                break
            ot += chr(table[value])
        tid = struct.unpack_from("<H", template, 0x0C)[0]
        fixed_trainer = tid != 0 or struct.unpack_from("<H", template, 0x68)[0] not in (0, 0xFFFF)
        periods = match_periods(dates, language, species, fixed_trainer, ot, tid, template[0x84] & 0x7F)
        cards.append((species, card_id, language, title, template, periods))
    cards.sort(key=lambda c: (c[0], c[1], c[2]))

    lines, all_periods = [], []
    for species, card_id, language, title, template, periods in cards:
        tag = LANGUAGE_CODES.get(language, "???")
        lines.append(f"    {{{card_id}, {species}, {language}, {c_string(f'{title} ({tag})')}, "
                     f"{len(all_periods)}, {len(periods)},")
        all_periods += periods
        for j in range(0, 136, 17):
            lines.append("     " + " ".join(f"0x{b:02X}," for b in template[j:j + 17]))
        lines.append("    },")
    content = HEADER + '\n#include "core/data/events4.h"\n\nnamespace pktool::data::generated {\n\n'
    content += "// Pokemon Wonder Cards (Gen IV PCD): decrypted stored PK4 templates, sorted by species.\n"
    content += "const Event4 kEvents4[] = {\n" + "\n".join(lines) + "\n};\n"
    content += f"const int kEvents4Count = {len(cards)};\n\n"
    content += "// Distribution periods (Bulbapedia, via tools/event_dates.csv) of the cards above.\n"
    content += emit_periods("kEventPeriods4", all_periods)
    content += "\n}  // namespace pktool::data::generated\n"
    (out / "events4_data.cpp").write_text(content, encoding="ascii")
    dated = sum(1 for c in cards if c[5])
    print(f"events4: {len(cards)} Pokemon cards, {dated} with distribution periods")


PGF_SIZE = 0xCC
PGF_POKEMON_BYTES = 0x60  # the Pokemon part of a PGF; the card title and metadata follow


def utf16_field(data: bytes) -> str:
    text = ""
    for (value,) in struct.iter_unpack("<H", data):
        if value in (0x0000, 0xFFFF):
            break
        text += chr(value)
    return text


def gen_events5(core: Path, out: Path, species_names: list[str]) -> None:
    """Pokemon Wonder Cards (PGF) from PKHeX's Mystery Gift database."""
    data = (core / "Resources" / "legality" / "mgdb" / "pgf.pkl").read_bytes()
    count = len(data) // (PGF_SIZE + 1)  # one receivability byte per card is packed at the end
    dates = load_event_dates(5)
    cards = []
    for i in range(count):
        card = data[i * PGF_SIZE:(i + 1) * PGF_SIZE]
        if card[0xB3] != 1:  # 1 = Pokemon (items and Pass Powers are skipped)
            continue
        receive = data[count * PGF_SIZE + i]
        restrict_version, restrict_language = receive & 0x0F, receive >> 4
        species = struct.unpack_from("<H", card, 0x1A)[0]
        if not 0 < species <= MAX_SPECIES_G5:
            raise SystemExit(f"pgf card {i}: bad species {species}")
        language = card[0x1D] or restrict_language
        is_egg = card[0x5C] == 1
        title = " ".join(utf16_field(card[0x60:0x60 + 37 * 2]).split())
        # The DS fonts cover Latin text only: other titles get a generic name.
        if not title or any(ord(ch) > 0x24F for ch in title):
            title = f"{species_names[species]} {'egg' if is_egg else 'event'}"
        day, month, year = card[0xAC], card[0xAD], struct.unpack_from("<H", card, 0xAE)[0]
        card_date = (year - 2000, month, day) if 2000 <= year < 2100 and 1 <= month <= 12 and day else (0, 0, 0)
        card_id = struct.unpack_from("<H", card, 0xB0)[0]
        ot = "" if is_egg else utf16_field(card[0x4A:0x4A + 16])
        tid = struct.unpack_from("<H", card, 0x00)[0]
        periods = match_periods(dates, restrict_language or language, species, bool(ot), ot, tid, card[0x5B])
        # The card's own date (the day it was received when it was dumped) is a
        # proven valid day even when Bulbapedia's periods miss it.
        if periods and card_date[1]:
            dumped = date(2000 + card_date[0], card_date[1], card_date[2])
            if not any(a <= dumped <= b for a, b in periods):
                periods = sorted(periods + [(dumped, dumped)])
        cards.append((species, card_id, language, restrict_version, restrict_language, card_date, title,
                      card[:PGF_POKEMON_BYTES], periods))
    cards.sort(key=lambda c: (c[0], c[1], c[2]))

    lines, all_periods = [], []
    for species, card_id, language, rversion, rlanguage, card_date, title, pgf, periods in cards:
        # Tag the distribution region (the Pokemon's own language may differ).
        tag = LANGUAGE_CODES.get(rlanguage or language, "ALL")
        lines.append(f"    {{{card_id}, {species}, {rversion}, {rlanguage}, {{{card_date[0]}, {card_date[1]}, {card_date[2]}}}, "
                     f"{c_string(f'{title} ({tag})')}, {len(all_periods)}, {len(periods)},")
        all_periods += periods
        for j in range(0, PGF_POKEMON_BYTES, 16):
            lines.append("     " + " ".join(f"0x{b:02X}," for b in pgf[j:j + 16]))
        lines.append("    },")
    content = HEADER + '\n#include "core/data/events5.h"\n\nnamespace pktool::data::generated {\n\n'
    content += "// Pokemon Wonder Cards (Gen V PGF): Pokemon part of each card, sorted by species.\n"
    content += "const Event5 kEvents5[] = {\n" + "\n".join(lines) + "\n};\n"
    content += f"const int kEvents5Count = {len(cards)};\n\n"
    content += "// Distribution periods (Bulbapedia, via tools/event_dates.csv) of the cards above.\n"
    content += emit_periods("kEventPeriods5", all_periods)
    content += "\n}  // namespace pktool::data::generated\n"
    (out / "events5_data.cpp").write_text(content, encoding="ascii")
    dated = sum(1 for c in cards if c[8])
    print(f"events5: {len(cards)} Pokemon cards, {dated} with distribution periods")


