def gen_dreamworld5(core: Path, out: Path) -> None:
    """Dream World (Entree Forest) encounters and N's Pokemon of B2/W2 (core/data/dreamworld5.h)."""
    base = core / "Legality" / "Encounters"

    # Pokemon Global Link promotions can be language-locked (bit 0 JPN, 1 KOR, 2 international).
    promo = (base / "Templates" / "Gen5" / "GlobalLinkPromotion.cs").read_text(encoding="utf-8")
    flags = {"None": 0, "Japanese": 1, "Korean": 2, "International": 4}
    aliases = dict(flags, NotInt=3, NotKor=5, All=7)
    languages = {}
    body = re.search(r"GetLanguages\(\) => promotion switch(.*?)\};", promo, re.S).group(1)
    for name, lang in re.findall(r"(\w+) => (\w+),", body):
        languages[name] = aliases[lang]

    rows = []
    entry_re = re.compile(r"^\s*new\s*\(\s*(\d+)\s*,\s*(\d+)((?:\s*,\s*\d+)*)((?:\s*,\s*\w+\s*:\s*\w+)*)\s*\)")
    for file, array, versions in (("Encounters5BW.cs", "DreamWorld_BW", 3), ("Encounters5B2W2.cs", "DreamWorld_B2W2", 12),
                                  ("Encounters5DR.cs", "DreamWorld_Common", 15)):
        text = (base / "Data" / "Gen5" / file).read_text(encoding="utf-8")
        match = re.search(array + r"\s*=\s*DreamWorldEntry\.GetArray\(\w+,\s*\[(.*?)\n    \]\);", text, re.S)
        if not match:
            raise SystemExit(f"{file}: {array} not found")
        for line in match.group(1).splitlines():
            m = entry_re.match(line)
            if not m:
                continue
            moves = [int(v) for v in re.findall(r"\d+", m.group(3))]
            named = dict(re.findall(r"(\w+)\s*:\s*(\w+)", m.group(4)))
            promotion = named.get("Promotion", "NotPromotion")
            rows.append({
                "species": int(m.group(1)), "level": int(m.group(2)), "moves": moves + [0] * (3 - len(moves)),
                "form": int(named["Form"]) if "Form" in named else None,
                "gender": int(named.get("Gender", 255)), "versions": versions,
                "languages": languages.get(promotion, 7),
            })
    if not 200 < len(rows) < 400:
        raise SystemExit(f"unexpected Dream World entry count: {len(rows)}")

    # Only species with several Dream World forms (Shellos, Basculin) pin the form.
    forms = {}
    for r in rows:
        forms.setdefault(r["species"], set()).add(r["form"] or 0)
    rows.sort(key=lambda r: r["species"])  # stable: keeps the source order within a species
    entries = []
    for r in rows:
        form = (r["form"] or 0) if len(forms[r["species"]]) > 1 else 255
        entries.append("{%d, {%s}, %d, %d, %d, %d, %d}," % (r["species"], ", ".join(map(str, r["moves"])), r["level"],
                                                              form, r["gender"], r["versions"], r["languages"]))

    # N's Pokemon (B2/W2): fixed PID, TID 2, SID 0, all IVs 30.
    text = (base / "Data" / "Gen5" / "Encounters5B2W2.cs").read_text(encoding="utf-8")
    block = re.search(r"Encounter_B2W2_N\s*=\s*\[(.*?)\n    \];", text, re.S).group(1)
    abilities = {"OnlyFirst": 0, "OnlySecond": 1, "OnlyHidden": 2}
    n_rows = []
    for m in re.finditer(r"new\(0x([0-9A-Fa-f]+)\)\s*\{([^}]*)\}", block):
        f = dict(re.findall(r"(\w+)\s*=\s*(\w+(?:\.\w+)?)", m.group(2)))
        n_rows.append("{0x%sU, %d, %d, %d, %d, %d}," % (m.group(1).upper(), int(f["Species"]), int(f["Level"], 10),
                                                         int(f["Location"], 10), NATURES.index(f["Nature"].split(".")[1]),
                                                         abilities[f["Ability"]]))
    if len(n_rows) != 15:
        raise SystemExit(f"unexpected N's Pokemon count: {len(n_rows)}")

    # Dream Radar (B2/W2): species, form and whether the hidden ability is implied (Rotom: abilities 1/2).
    text = (base / "Data" / "Gen5" / "Encounters5DR.cs").read_text(encoding="utf-8")
    block = re.search(r"Encounter_DreamRadar\s*=\s*\[(.*?)\n    \];", text, re.S).group(1)
    radar_rows = []
    for m in re.finditer(r"new\(\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*(\w+))?\s*\)", block):
        radar_rows.append("{%d, %d, %d}," % (int(m.group(1)), int(m.group(2)), 1 if m.group(3) == "Any12" else 0))
    if len(radar_rows) != 26:
        raise SystemExit(f"unexpected Dream Radar entry count: {len(radar_rows)}")

    content = HEADER + '\n#include "core/data/dreamworld5.h"\n\nnamespace pktool::data::generated {\n\n'
    content += "// Dream World / Entree Forest encounters (Black/White, Black 2/White 2 and shared), sorted by species.\n"
    content += "const DreamWorld5 kDreamWorld5[] = {\n" + "\n".join("    " + e for e in entries) + "\n};\n"
    content += f"const int kDreamWorld5Count = {len(entries)};\n\n"
    content += "// N's Pokemon in Black 2 / White 2.\n"
    content += "const NPokemon5 kNPokemon5[] = {\n" + "\n".join("    " + e for e in n_rows) + "\n};\n"
    content += f"const int kNPokemon5Count = {len(n_rows)};\n\n"
    content += "// Dream Radar encounters (Black 2 / White 2).\n"
    content += "const DreamRadar5 kDreamRadar5[] = {\n" + "\n".join("    " + e for e in radar_rows) + "\n};\n"
    content += f"const int kDreamRadar5Count = {len(radar_rows)};\n"
    content += "\n}  // namespace pktool::data::generated\n"
    (out / "dreamworld5_data.cpp").write_text(content, encoding="ascii")
    print(f"dreamworld5: {len(entries)} Dream World entries, {len(n_rows)} N's Pokemon, {len(radar_rows)} Dream Radar")


def gen_charmap4(core: Path, out: Path) -> None:
    source = (core / "PKM" / "Strings" / "StringConverter4Util.cs").read_text(encoding="utf-8")
    table = parse_char_table(source, "TableINT")
    korean = parse_char_table(source, "TableKOR")
    struct.pack(f"<{len(table)}H", *table)  # sanity: all values fit in 16 bits
    struct.pack(f"<{len(korean)}H", *korean)
    kor_start = int(re.search(r"TableKORStart\s*=\s*(0x[0-9A-Fa-f]+)", source).group(1), 16)

    def rows(values: list[int], base: int) -> str:
        lines = []
        for i in range(0, len(values), 16):
            chunk = ", ".join(f"0x{v:04X}" for v in values[i:i + 16])
            lines.append(f"    {chunk},  // 0x{base + i:03X}")
        return "\n".join(lines)

    content = HEADER + '\n#include "core/text/gen4_text.h"\n\nnamespace pktool::text::generated {\n\n'
    content += "// Generation IV/V-DS international glyph table: game value -> Unicode.\n"
    content += "// 0xFFFF marks values without a character.\n"
