# Move source flags (must match core/data/learn4.h).
SRC_LEVEL, SRC_MACHINE, SRC_TUTOR, SRC_EGG = 1, 2, 4, 8


def pack_learnsets(moves: dict, max_species: int) -> tuple[bytes, list[int]]:
    """Packs learnsets into the byte stream read by data::decodeLearn (core/data/learn4.cpp).

    moves[species][move] = [sources, minLevel]. Per species the entries are sorted by move
    and each one is coded as:
      - move delta (against the previous move, 0 at the start) 1-15 and the 4 source bits
        in one byte: delta << 4 | sources;
      - larger deltas: the byte sources, then delta - 16 (0-254) or 255 and the delta as a
        little-endian u16;
      - one extra byte, the lowest level-up level, when the sources include SRC_LEVEL.
    Returns the stream and the byte offset of each species (max_species + 2 entries, the
    last one being the end of the stream).
    """
    data = bytearray()
    index = []
    for sp in range(max_species + 1):
        index.append(len(data))
        prev = 0
        for move in sorted(moves[sp]):
            flags, level = moves[sp][move]
            if not 0 < flags < 16:
                raise SystemExit(f"learnset sources out of range: species {sp} move {move} flags {flags}")
            delta = move - prev
            prev = move
            if delta < 16:
                data.append(delta << 4 | flags)
            else:
                data.append(flags)
                if delta - 16 < 255:
                    data.append(delta - 16)
                else:
                    data += bytes([255]) + struct.pack("<H", delta)
            if flags & SRC_LEVEL:
                data.append(level)
    index.append(len(data))
    return bytes(data), index


def learn_stream_rows(data: bytes) -> str:
    return "\n".join("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16))


def binlinker(data: bytes, ident: bytes, wide: bool):
    """Entries of a PKHeX BinLinker file (16- or 32-bit offsets)."""
    if data[:2] != ident:
        raise SystemExit(f"unexpected BinLinker identifier {data[:2]!r}, wanted {ident!r}")
    count = struct.unpack_from("<H", data, 2)[0]
    size, fmt = (4, "<I") if wide else (2, "<H")
    offsets = [struct.unpack_from(fmt, data, 4 + i * size)[0] for i in range(count + 1)]
    return [data[offsets[i]:offsets[i + 1]] for i in range(count)]


def gen_learn4(core: Path, out: Path) -> None:
    res = core / "Resources" / "byte"
    moves = {sp: {} for sp in range(MAX_SPECIES_G4 + 1)}  # species -> move -> [flags, minLevel]

    def add(sp, move, flag, level=0):
        if move == 0 or move > MAX_MOVE_G4:
            return
        entry = moves[sp].setdefault(move, [0, 255])
        entry[0] |= flag
        if flag == SRC_LEVEL:
            entry[1] = min(entry[1], level)

    for name, ident in (("dp", b"dp"), ("pt", b"pt"), ("hgss", b"hs")):
        entries = binlinker((res / "levelup" / f"lvlmove_{name}.pkl").read_bytes(), ident, False)
        for sp in range(1, MAX_SPECIES_G4 + 1):
            blob = entries[sp]
            count = len(blob) // 3
            mv = struct.unpack_from(f"<{count}H", blob, 0)
            lv = blob[count * 2:count * 3]
            for m, l in zip(mv, lv):
                add(sp, m, SRC_LEVEL, l)

    for name, ident in (("dppt", b"dp"), ("hgss", b"hs")):
        entries = binlinker((res / "eggmove" / f"eggmove_{name}.pkl").read_bytes(), ident, False)
        for sp in range(1, min(len(entries), MAX_SPECIES_G4 + 1)):
            blob = entries[sp]
            for m in struct.unpack_from(f"<{len(blob) // 2}H", blob, 0):
                add(sp, m, SRC_EGG)

    for name, hms in (("pt", HM_MOVES_DPPT), ("hgss", HM_MOVES_HGSS)):
        raw = (res / "personal" / f"personal_{name}").read_bytes()
        machines = TM_MOVES4 + hms
        for sp in range(1, MAX_SPECIES_G4 + 1):
            bits = raw[sp * PERSONAL4_SIZE + 0x1C: sp * PERSONAL4_SIZE + 0x1C + 13]
            for i, m in enumerate(machines):
                if bits[i >> 3] & (1 << (i & 7)):
                    add(sp, m, SRC_MACHINE)

    tutors = binlinker((res / "personal" / "tutors_g4.pkl").read_bytes(), b"g4", True)
    for sp in range(1, MAX_SPECIES_G4 + 1):
        blob = tutors[sp]
        for i, m in enumerate(TUTOR_MOVES4):
            if i >> 3 < len(blob) and blob[i >> 3] & (1 << (i & 7)):
                add(sp, m, SRC_TUTOR)
    for move, species in SPECIAL_TUTORS4.items():
        for sp in species:
            add(sp, move, SRC_TUTOR)

    # Pre-evolutions: evos_g4 lists, per species, what it evolves into.
    # Records: type, -, u16 argument, u16 species, form, level (level-based methods only).
    # A species has a minimum level only if every way to evolve into it needs one.
    pre = [0] * (MAX_SPECIES_G4 + 1)
    evolve_levels = [[] for _ in range(MAX_SPECIES_G4 + 1)]
    evos = binlinker((res / "evolve" / "evos_g4.pkl").read_bytes(), b"g4", False)
    for sp in range(1, min(len(evos), MAX_SPECIES_G4 + 1)):
        blob = evos[sp]
        for off in range(0, len(blob), 8):
            target = struct.unpack_from("<H", blob, off + 4)[0]
            if 0 < target <= MAX_SPECIES_G4:
                if pre[target] == 0:
                    pre[target] = sp
                evolve_levels[target].append(blob[off + 7])
    evolve_level = [min(levels) if levels and all(levels) else 0 for levels in evolve_levels]

    for sp in moves:
        for entry in moves[sp].values():
            if not entry[0] & SRC_LEVEL:
                entry[1] = 0
    stream, index = pack_learnsets(moves, MAX_SPECIES_G4)
    count = sum(len(m) for m in moves.values())

    idx_lines = []
    for i in range(0, len(index), 16):
        idx_lines.append("    " + ", ".join(str(v) for v in index[i:i + 16]) + ",")
    pre_lines = []
    for i in range(0, len(pre), 16):
        pre_lines.append("    " + ", ".join(str(v) for v in pre[i:i + 16]) + ",")

    content = HEADER + '\n#include "core/data/learn4.h"\n\nnamespace pktool::data::generated {\n\n'
    content += "// Moves each species can learn in Gen IV (union of D/P, Pt and HG/SS), sorted by move\n"
    content += "// and packed as described in core/data/learn4.h.\n"
    content += "const uint8_t kLearn4[] = {\n" + learn_stream_rows(stream) + "\n};\n\n"
    content += "// kLearn4 range of species s: [kLearn4Index[s], kLearn4Index[s + 1]).\n"
    content += "const uint32_t kLearn4Index[] = {\n" + "\n".join(idx_lines) + "\n};\n\n"
    content += "// Pre-evolution of each species (0 = none).\n"
    content += "const uint16_t kPreEvolution4[] = {\n" + "\n".join(pre_lines) + "\n};\n\n"
    lvl_lines = []
    for i in range(0, len(evolve_level), 16):
        lvl_lines.append("    " + ", ".join(str(v) for v in evolve_level[i:i + 16]) + ",")
    content += "// Level at which each species evolves from its pre-evolution (0 = not level-based).\n"
    content += "const uint8_t kEvolveLevel4[] = {\n" + "\n".join(lvl_lines) + "\n};\n"
    content += "\n}  // namespace pktool::data::generated\n"
    (out / "learn4_data.cpp").write_text(content, encoding="ascii")
    print(f"learn4: {count} entries in {len(stream)} bytes")


