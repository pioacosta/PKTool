def cs_array(source: str, name: str) -> list[str]:
    """Lines of a C# collection-expression array `Name = [ ... ];`."""
    match = re.search(rf"\b{name}\s*=\s*\[\s*\n(.*?)\n\s*\];", source, re.S)
    if match is None:
        raise SystemExit(f"array {name} not found")
    return match.group(1).splitlines()


def cs_props(body: str) -> dict:
    props = {}
    for m in re.finditer(r'(\w+) = (new\([^)]*\)|\(int\)\w+|"[^"]*"|[\w.]+)', body):
        props[m.group(1)] = m.group(2)
    return props


def cs_moves(value: str | None) -> list[int]:
    moves = [int(v) for v in re.findall(r"\d+", value or "")]
    return (moves + [0] * 4)[:4]


