def parse_item_spans(source: str) -> dict[str, list[int]]:
    """All `ReadOnlySpan<ushort> Name => [ ... ];` literals of a C# file."""
    spans = {}
    for name, body in re.findall(r"ReadOnlySpan<ushort>\s+(\w+)\s*=>\s*\[(.*?)\];", source, re.S):
        body = re.sub(r"//[^\n]*", "", body)
        spans[name] = [int(v) for v in re.findall(r"\d+", body)]
    return spans


# Languages packed into assets/nitrofs/lang/<code>.bin (English stays compiled in).
LANG_PACKS = {"ja": 1, "fr": 3, "it": 4, "de": 5, "es": 7, "ko": 8}  # code -> game language ID


def gen_lang_packs(core: Path, assets: Path) -> None:
    """Species, move, ability, nature, item and Gen III item names per language.

    File "PKN1": magic, u8 language ID, u8 table count (6), u16 count per table,
    u32 string offsets (all tables in order, relative to the pool), then the pool
    of NUL-terminated UTF-8 strings. Names PKHeX leaves empty fall back to the
    English one and names that are "???" in English stay "???" (they mark IDs
    that do not exist; the code compares against that string)."""
    text = core / "Resources" / "text"
    en = {
        "species": read_lines(text / "other" / "en" / "text_Species_en.txt", MAX_SPECIES_G5 + 1),
        "moves": read_lines(text / "other" / "en" / "text_Moves_en.txt", MAX_MOVE_G5 + 1),
        "abilities": read_lines(text / "other" / "en" / "text_Abilities_en.txt", MAX_ABILITY_G5 + 1),
        "natures": read_lines(text / "other" / "en" / "text_Natures_en.txt", 25),
        "items": read_lines(text / "items" / "text_Items_en.txt", MAX_ITEM_G5 + 1),
        "items3": read_text_auto(text / "items" / "gen3" / "text_ItemsG3_en.txt").splitlines(),
    }
    out_dir = assets / "lang"
    out_dir.mkdir(parents=True, exist_ok=True)
    for code, lang_id in LANG_PACKS.items():
        files = {
            "species": text / "other" / code / f"text_Species_{code}.txt",
            "moves": text / "other" / code / f"text_Moves_{code}.txt",
            "abilities": text / "other" / code / f"text_Abilities_{code}.txt",
            "natures": text / "other" / code / f"text_Natures_{code}.txt",
            "items": text / "items" / f"text_Items_{code}.txt",
            "items3": text / "items" / "gen3" / f"text_ItemsG3_{code}.txt",
        }
        tables = []
        for kind, english in en.items():
            lines = read_text_auto(files[kind]).splitlines() if files[kind].exists() else []
            names = []
            for i, fallback in enumerate(english):
                name = lines[i].strip() if i < len(lines) else ""
                if fallback == "???" or not name:
                    name = fallback
                names.append(name)
            if kind != "natures":
                names[0] = ""  # ID 0 is "(None)": the code keeps the English one
            tables.append(names)
        pool = bytearray()
        offsets = []
        for names in tables:
            for name in names:
                offsets.append(len(pool))
                pool += name.encode("utf-8") + b"\0"
        blob = b"PKN1" + struct.pack("<BB", lang_id, len(tables))
        blob += struct.pack(f"<{len(tables)}H", *[len(t) for t in tables])
        blob += struct.pack(f"<{len(offsets)}I", *offsets) + bytes(pool)
        (out_dir / f"{code}.bin").write_bytes(blob)
        print(f"lang {code}: {len(blob)} bytes")


def gen_items(core: Path, out: Path) -> None:
    """Bag pockets of every game: legal items, slot offsets and quantity limits,
    plus the Gen III item names (Gen III IDs differ from Gen IV's)."""
    items_dir = core / "Items"
    if not (items_dir / "ItemStorage3RS.cs").exists():
        raise SystemExit(f"{items_dir}: missing; run `git sparse-checkout add PKHeX.Core/Items` in PKHeX")
    converter = (core / "PKM" / "Util" / "Conversion" / "ItemConverter.cs").read_text(encoding="utf-8")
    hm_ranges = {}
    for gen in (3, 4):
        match = re.search(rf"IsItemHM{gen}\(ushort item\) => item is \(>= (\d+) and <= (\d+)\)", converter)
        hm_ranges[gen] = (int(match.group(1)), int(match.group(2)))

    def source(name: str) -> str:
        path = items_dir / f"{name}.cs"
        if not path.exists():
            path = items_dir / "Bags" / f"{name}.cs"
        return path.read_text(encoding="utf-8")

    tables = ""
    specs = ""
    for layout, storage_name, base_name, bag_name, gen in BAG_GAMES:
        storage = source(storage_name)
        spans = parse_item_spans(storage)
        if base_name:
            spans = {**parse_item_spans(source(base_name)), **spans}
        by_type = dict(re.findall(r"InventoryType\.(\w+) => (\w+),", storage))
        bag = source(bag_name)
        if gen == 3:  # new(offset, slots, max quantity, info, type)
            pouches = [(int(o, 16), int(size), int(maxc), kind)
                       for o, size, maxc, kind in re.findall(r"new\((0x[0-9A-Fa-f]+), (\d+), (\d+), info, (\w+)\)", bag)]
        else:  # new(offset, max quantity, info, type): one slot per possible item
            pouches = [(int(o, 16), None, int(maxc), kind)
                       for o, maxc, kind in re.findall(r"new\((0x[0-9A-Fa-f]+), (\d+), info, (\w+)\)", bag)]
        rows = []
        for offset, size, max_count, kind in pouches:
            if kind == "PCItems":
                continue  # Gen III PC storage is out of scope
            ids = spans[by_type[kind]]
            if len(set(ids)) != len(ids):
                raise SystemExit(f"{layout} {kind}: duplicate item IDs")
            capacity = size if size is not None else len(ids)
            label, enum = POCKET_KINDS[kind]
            single = hm_ranges.get(gen, (0, 0)) if kind == "TMHMs" else (0, 0)
            var = f"k{layout}{enum}"
            tables += f"const uint16_t {var}[] = {{\n"
            tables += ",\n".join("    " + ", ".join(str(v) for v in ids[i:i + 16]) for i in range(0, len(ids), 16))
            tables += ",\n};\n"
            rows.append(
                f"    {{{c_string(label)}, PocketKind::{enum}, 0x{offset:X}, {capacity}, {max_count}, "
                f"{single[0]}, {single[1]}, {var}, {len(ids)}}},"
            )
        specs += f"const PocketSpec kBag{layout}[] = {{\n" + "\n".join(rows) + "\n};\n"
        specs += f"const int kBag{layout}Count = {len(rows)};\n\n"
        print(f"items: {layout}: {len(rows)} pockets")

    names3 = (core / "Resources" / "text" / "items" / "gen3" / "text_ItemsG3_en.txt").read_text(encoding="utf-16").splitlines()
    names3[0] = "(None)"
    content = HEADER + '\n#include "core/data/items.h"\n\nnamespace pktool::data::generated {\n\n'
    content += tables + "\n" + specs
    content += "// Gen III item names, indexed by Gen III item ID.\n" + emit_string_table("kItemNames3", names3)
    content += "\n}  // namespace pktool::data::generated\n"
    (out / "items_data.cpp").write_text(content, encoding="ascii")


