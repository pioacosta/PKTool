def cs_consts(source: str, known: dict) -> dict:
    """`const char NAME = 'x';` declarations (values may reference StringConverter1)."""
    consts = dict(known)
    for name, value in re.findall(r"const char (\w+) = ('(?:\\.|[^'\\])'|\w+(?:\.\w+)?);", source):
        if value.startswith("'"):
            literal = value[1:-1]
            consts[name] = 0 if literal == "\\0" else ord({"\\'": "'", "\\\\": "\\"}.get(literal, literal))
        else:
            ref = value.split(".")[-1]
            consts[name] = consts[ref] if ref in consts else known[ref]
    return consts


def parse_gb_char_table(source: str, table: str, consts: dict) -> list[int]:
    match = re.search(rf"{table}\s*=>[^\[]*\[(.*?)\n\s*\];", source, re.S)
    if not match:
        raise SystemExit(f"could not find {table}")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    values = []
    for token in re.finditer(r"'(\\.|[^'\\])'|\b([A-Z][A-Z0-9]{2})\b", body):
        if token.group(2):
            values.append(0xFFFF if token.group(2) == "NUL" else consts[token.group(2)])
        else:
            literal = token.group(1)
            values.append(ord({"\\'": "'", "\\\\": "\\"}.get(literal, literal)))
    if len(values) != 256:
        raise SystemExit(f"{table}: expected 256 characters, found {len(values)}")
    return values


def gb_rows(values, per=16):
    return ",\n".join("    " + ", ".join(str(v) for v in values[i:i + per]) for i in range(0, len(values), per))


