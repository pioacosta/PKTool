    def rows(values, per=16):
        return ",\n".join("    " + ", ".join(str(v) for v in values[i:i + per]) for i in range(0, len(values), per))

    content = HEADER + '\n#include "core/data/gen3.h"\n\nnamespace pktool::data::generated {\n\n'
