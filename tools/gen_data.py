def gen_moves5(core: Path, out: Path) -> None:
    source = (core / "Moves" / "MoveInfo5.cs").read_text(encoding="utf-8")
    match = re.search(r"PP\s*=>\s*\[(.*?)\];", source, re.S)
    if not match:
        raise SystemExit("could not find the Gen V PP table")
    pp = [int(v, 10) for v in re.findall(r"\d+", re.sub(r"//[^\n]*", "", match.group(1)))][:MAX_MOVE_G5 + 1]
    if len(pp) != MAX_MOVE_G5 + 1:
        raise SystemExit(f"Gen V PP table too short: {len(pp)}")
    lines = ["    " + ", ".join(str(v) for v in pp[i:i + 20]) + "," for i in range(0, len(pp), 20)]
    content = HEADER + '\n#include "core/data/moves.h"\n\nnamespace pktool::data::generated {\n\n'
    content += "// Base PP of moves 0-559 in Generation V.\n"
    content += "const uint8_t kMovePP5[] = {\n" + "\n".join(lines) + "\n};\n"
    content += f"const int kMovePP5Count = {len(pp)};\n"
    content += "\n}  // namespace pktool::data::generated\n"
    (out / "moves5.cpp").write_text(content, encoding="ascii")


