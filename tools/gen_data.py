def gen_names(core: Path, out: Path) -> None:
    text = core / "Resources" / "text"
    species = read_lines(text / "other" / "en" / "text_Species_en.txt", MAX_SPECIES_G5 + 1)
    moves = read_lines(text / "other" / "en" / "text_Moves_en.txt", MAX_MOVE_G5 + 1)
    abilities = read_lines(text / "other" / "en" / "text_Abilities_en.txt", MAX_ABILITY_G5 + 1)
    natures = read_lines(text / "other" / "en" / "text_Natures_en.txt", 25)
    items = read_lines(text / "items" / "text_Items_en.txt", MAX_ITEM_G5 + 1)

    species[0] = "(None)"
    moves[0] = "(None)"
    abilities[0] = "(None)"
    items[0] = "(None)"

    content = HEADER + '\n#include "core/data/names.h"\n\nnamespace pktool::data::generated {\n\n'
    content += emit_string_table("kSpeciesNames", species) + "\n"
    content += emit_string_table("kMoveNames", moves) + "\n"
    content += emit_string_table("kAbilityNames", abilities) + "\n"
    content += emit_string_table("kNatureNames", natures) + "\n"
    content += emit_string_table("kItemNames", items)
    content += "\n}  // namespace pktool::data::generated\n"
    (out / "names_en.cpp").write_text(content, encoding="ascii")


def gen_personal4(core: Path, out: Path) -> None:
    raw = (core / "Resources" / "byte" / "personal" / "personal_hgss").read_bytes()
    if len(raw) % PERSONAL4_SIZE:
        raise SystemExit("personal_hgss: unexpected size")
    rows = []
    for species in range(MAX_SPECIES_G4 + 1):
        entry = raw[species * PERSONAL4_SIZE:(species + 1) * PERSONAL4_SIZE]
        hp, atk, dfn, spe, spa, spd = entry[0:6]
        gender, growth = entry[0x10], entry[0x13]
        egg1, egg2 = entry[0x14], entry[0x15]
        ability1, ability2 = entry[0x16], entry[0x17]
        rows.append(
            f"    {{{{{hp}, {atk}, {dfn}, {spe}, {spa}, {spd}}}, "
            f"{gender}, {growth}, {{{ability1}, {ability2}}}, {{{egg1}, {egg2}}}, 0, {entry[0x11]}}},"
        )

    growth = parse_growth_tables((core / "PKM" / "Util" / "Experience.cs").read_text(encoding="utf-8"))
    growth_rows = []
    for table in growth:
        chunks = [", ".join(str(v) for v in table[i:i + 10]) for i in range(0, 100, 10)]
        growth_rows.append("    {\n        " + ",\n        ".join(chunks) + ",\n    },")

    content = HEADER + '\n#include "core/data/personal.h"\n\nnamespace pktool::data::generated {\n\n'
    content += "// Base-form personal data for species 0-493 (HeartGold/SoulSilver tables).\n"
    content += "const PersonalInfo kPersonal4[] = {\n" + "\n".join(rows) + "\n};\n"
    content += f"const int kPersonal4Count = {len(rows)};\n\n"
    content += "// Total EXP required for levels 1-100, per growth rate.\n"
    content += "const uint32_t kExpTable[6][100] = {\n" + "\n".join(growth_rows) + "\n};\n"
    content += "\n}  // namespace pktool::data::generated\n"
    (out / "personal4.cpp").write_text(content, encoding="ascii")


